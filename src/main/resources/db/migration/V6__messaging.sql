create table conversations (
  id varchar(255) not null,
  kind varchar(32) not null,
  title varchar(255),
  created_by varchar(255) not null,
  created_at timestamp with time zone not null,
  updated_at timestamp with time zone not null,
  primary key (id)
);

create table conversation_participants (
  id bigint generated by default as identity,
  conversation_id varchar(255) not null,
  user_id varchar(255) not null,
  last_read_at timestamp with time zone,
  joined_at timestamp with time zone not null,
  primary key (id)
);

alter table conversation_participants add constraint uk_conversation_participant unique (conversation_id, user_id);
create index idx_conversation_participants_user on conversation_participants (user_id);
create index idx_conversation_participants_conversation on conversation_participants (conversation_id);

create table messages (
  id varchar(255) not null,
  conversation_id varchar(255) not null,
  sender_id varchar(255) not null,
  text varchar(5000) not null,
  created_at timestamp with time zone not null,
  primary key (id)
);

create index idx_messages_conversation_created on messages (conversation_id, created_at);

alter table conversation_participants add constraint fk_conv_part_conv foreign key (conversation_id) references conversations (id);
alter table messages add constraint fk_messages_conversation foreign key (conversation_id) references conversations (id);
