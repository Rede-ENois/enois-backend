create table user_connections (
  id bigint generated by default as identity,
  requester_user_id varchar(255) not null,
  receiver_user_id varchar(255) not null,
  status varchar(32) not null,
  created_at timestamp not null,
  accepted_at timestamp,
  removed_at timestamp,
  primary key (id)
);

alter table user_connections add constraint uk_user_connection_pair unique (requester_user_id, receiver_user_id);
create index idx_user_connections_requester_status on user_connections (requester_user_id, status);
create index idx_user_connections_receiver_status on user_connections (receiver_user_id, status);
