create table password_reset_tokens (
  token varchar(255) not null,
  user_id varchar(255) not null,
  expires_at timestamp with time zone not null,
  used_at timestamp with time zone,
  created_at timestamp with time zone not null,
  primary key (token)
);

create index idx_password_reset_tokens_expires on password_reset_tokens (expires_at);
alter table password_reset_tokens add constraint fk_password_reset_tokens_user foreign key (user_id) references users (id);

create table user_external_identities (
  id bigint generated by default as identity,
  user_id varchar(255) not null,
  provider varchar(32) not null,
  external_user_id varchar(255) not null,
  email varchar(255),
  created_at timestamp with time zone not null,
  primary key (id)
);

alter table user_external_identities add constraint uk_user_external_identity unique (provider, external_user_id);
create index idx_user_external_identities_user on user_external_identities (user_id);
alter table user_external_identities add constraint fk_user_external_identities_user foreign key (user_id) references users (id);
